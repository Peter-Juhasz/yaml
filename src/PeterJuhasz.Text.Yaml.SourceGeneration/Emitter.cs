using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace PeterJuhasz.Text.Yaml.SourceGeneration;

internal static class Naming
{
	// members of the context and of object, which cannot be used as the names of the generated properties
	private static readonly string[] Reserved = ["Default", "Options", "GetTypeInfo", "Equals", "GetHashCode", "ToString", "GetType", "MemberwiseClone", "Finalize"];

	// the names are derived from the names of the types, colliding ones are qualified by their containing types, then by their namespaces
	public static void Assign(INamedTypeSymbol context, List<TypeSpec> types, List<DiagnosticInfo> diagnostics)
	{
		var reserved = new HashSet<string>(Reserved, StringComparer.Ordinal) { context.Name };
		foreach (var member in context.GetMembers())
		{
			reserved.Add(member.Name);
		}

		var used = new HashSet<string>(StringComparer.Ordinal);
		foreach (var spec in types.Where(static t => t.ExplicitPropertyName is not null))
		{
			if (!used.Add(spec.ExplicitPropertyName!))
			{
				diagnostics.Add(DiagnosticInfo.Create(Descriptors.DuplicatePropertyName, context.Locations.FirstOrDefault(), spec.ExplicitPropertyName!, context.Name));
			}

			spec.PropertyName = spec.ExplicitPropertyName!;
		}

		var pending = types.Where(static t => t.ExplicitPropertyName is null).ToList();
		for (var level = 0; level < 3 && pending.Count > 0; level++)
		{
			var candidates = pending.Select(t => (Spec: t, Name: Adjust(GetName(t.Type, level), reserved))).ToList();
			var counts = candidates.GroupBy(static c => c.Name).ToDictionary(static g => g.Key, static g => g.Count());
			pending = [];
			foreach (var (spec, name) in candidates)
			{
				if (counts[name] is 1 && used.Add(name))
				{
					spec.PropertyName = name;
				}
				else
				{
					pending.Add(spec);
				}
			}
		}

		// types, whose qualified names collide, like the same generic types of different types, are numbered
		foreach (var spec in pending)
		{
			var name = Adjust(GetName(spec.Type, 2), reserved);
			var index = 2;
			while (!used.Add($"{name}{index}"))
			{
				index++;
			}
			spec.PropertyName = $"{name}{index}";
		}

		foreach (var spec in types)
		{
			spec.Core?.PropertyName = spec.PropertyName;
		}
	}

	private static string Adjust(string name, HashSet<string> reserved) => reserved.Contains(name) || name.StartsWith("__", StringComparison.Ordinal) || SyntaxFacts.GetKeywordKind(name) is not SyntaxKind.None ? name + "TypeInfo" : name;

	private static string GetName(ITypeSymbol type, int level) => type switch
	{
		IArrayTypeSymbol array => GetName(array.ElementType, level) + "Array",
		INamedTypeSymbol named => GetPrefix(named, level) + named.Name + String.Concat(named.TypeArguments.Select(t => GetName(t, level))),
		_ => type.Name,
	};

	private static string GetPrefix(INamedTypeSymbol type, int level)
	{
		if (level is 0)
		{
			return "";
		}

		var builder = new StringBuilder();
		if (level >= 2 && type.ContainingNamespace is { IsGlobalNamespace: false } ns)
		{
			builder.Append(ns.ToDisplayString().Replace(".", ""));
		}

		var containing = new Stack<string>();
		for (var current = type.ContainingType; current is not null; current = current.ContainingType)
		{
			containing.Push(current.Name);
		}

		foreach (var name in containing)
		{
			builder.Append(name);
		}

		return builder.ToString();
	}
}

internal static class Emitter
{
	private const string TypeInfo = "global::PeterJuhasz.Text.Yaml.Serialization.Metadata.YamlTypeInfo";
	private const string Services = "global::PeterJuhasz.Text.Yaml.Serialization.Metadata.YamlMetadataServices";

	public static string Emit(INamedTypeSymbol context, ContextParser parser, bool generateConstructors, bool generateDefault)
	{
		var writer = new CodeWriter();
		writer.Line("// <auto-generated/>");
		writer.Line("#nullable enable annotations");
		writer.Line("#nullable disable warnings");
		writer.Line("#pragma warning disable CS0612, CS0618 // obsolete types and members are serialized as well");
		writer.Line();

		if (context.ContainingNamespace is { IsGlobalNamespace: false } ns)
		{
			writer.Line($"namespace {ns.ToDisplayString()};");
			writer.Line();
		}

		var containing = new Stack<INamedTypeSymbol>();
		for (var current = context.ContainingType; current is not null; current = current.ContainingType)
		{
			containing.Push(current);
		}

		foreach (var type in containing)
		{
			writer.Open($"partial {GetKeyword(type)} {type.Name}");
		}

		var contextName = context.ToDisplayString(ContextParser.Format);
		writer.Open($"partial class {context.Name}");

		if (generateDefault)
		{
			writer.Line($"private static {contextName}? __default;");
			writer.Line();
			writer.Line("// the instance with the default options");
			writer.Line($"public static {contextName} Default => __default ??= new {contextName}();");
			writer.Line();
		}

		if (generateConstructors)
		{
			writer.Line($"public {context.Name}() : base(null)");
			writer.Line("{");
			writer.Line("}");
			writer.Line();
			writer.Line($"public {context.Name}(global::PeterJuhasz.Text.Yaml.Serialization.YamlSerializerOptions? options) : base(options)");
			writer.Line("{");
			writer.Line("}");
			writer.Line();
		}

		foreach (var spec in parser.Types)
		{
			writer.Line($"private {TypeInfo}<{spec.FullName}>? __{spec.PropertyName};");
			writer.Line();
			writer.Line($"public {TypeInfo}<{spec.FullName}> {spec.PropertyName} => __{spec.PropertyName} ??= __Create{spec.PropertyName}();");
			writer.Line();
			if (spec.Core is { } core)
			{
				writer.Line($"private {TypeInfo}<{core.FullName}>? __CoreField_{spec.PropertyName};");
				writer.Line();
				writer.Line($"private {TypeInfo}<{core.FullName}> __Core_{spec.PropertyName} => __CoreField_{spec.PropertyName} ??= __CreateCore_{spec.PropertyName}();");
				writer.Line();
			}
		}

		writer.Open($"public override {TypeInfo}? GetTypeInfo(global::System.Type type)");
		foreach (var spec in parser.Types)
		{
			writer.Line($"if (type == typeof({spec.FullName})) return this.{spec.PropertyName};");
		}
		writer.Line("return null;");
		writer.Close();

		foreach (var spec in parser.Types)
		{
			writer.Line();
			writer.Line($"private {TypeInfo}<{spec.FullName}> __Create{spec.PropertyName}() => {Create(spec)};");
			if (spec.Core is { } core)
			{
				writer.Line();
				writer.Line($"private {TypeInfo}<{core.FullName}> __CreateCore_{spec.PropertyName}() => {Create(core)};");
			}
		}

		foreach (var accessor in parser.Accessors)
		{
			writer.Line();
			writer.Line(accessor);
		}

		writer.Close();
		foreach (var _ in containing)
		{
			writer.Close();
		}

		return writer.ToString();
	}

	private static string GetKeyword(INamedTypeSymbol type) => (type.TypeKind, type.IsRecord) switch
	{
		(Microsoft.CodeAnalysis.TypeKind.Struct, true) => "record struct",
		(Microsoft.CodeAnalysis.TypeKind.Struct, false) => "struct",
		(Microsoft.CodeAnalysis.TypeKind.Interface, _) => "interface",
		(_, true) => "record",
		_ => "class",
	};

	private static string Create(TypeSpec spec) => spec.Kind switch
	{
		SpecKind.Untyped => $"{Services}.CreateUntypedInfo(this)",
		SpecKind.Node => $"{Services}.CreateNodeInfo<{spec.FullName}>(this)",
		SpecKind.Nullable => $"{Services}.CreateNullableInfo<{spec.Element!.FullName}>(this, {spec.Element.Accessor})",
		SpecKind.Scalar => $"{Services}.CreateScalarInfo<{spec.FullName}>(this)",
		SpecKind.Parsable => $"{Services}.CreateParsableInfo<{spec.FullName}>(this)",
		SpecKind.Enum => $"{Services}.CreateEnumInfo<{spec.FullName}>(this, [{String.Join(", ", spec.EnumMembers!.Select(static m => $"({ContextParser.Literal(m.Name)}, {ContextParser.Literal(m.ExplicitName)}, {m.Value})"))}], isFlags: {Bool(spec.IsFlags)})",
		SpecKind.Array => $"{Services}.CreateArrayInfo<{spec.Element!.FullName}>(this, {spec.Element.Accessor})",
		SpecKind.Collection => $"{Services}.CreateCollectionInfo<{spec.FullName}, {spec.Collection!.BuilderType}, {spec.Element!.FullName}>(this, {spec.Element.Accessor}, {spec.Collection.Create}, {spec.Collection.Add}, {spec.Collection.Convert}, isStack: {Bool(spec.Collection.IsStack)})",
		SpecKind.Dictionary => $"{Services}.CreateDictionaryInfo<{spec.FullName}, {spec.Collection!.BuilderType}, {spec.Key!.FullName}, {spec.Element!.FullName}>(this, {spec.Key.Accessor}, {spec.Element.Accessor}, {spec.Collection.Create}, {spec.Collection.Add}, {spec.Collection.Convert})",
		SpecKind.Object => CreateObject(spec, spec.Object!),
		SpecKind.Polymorphic => CreatePolymorphic(spec, spec.Polymorphic!),
		_ => $"{Services}.CreateUnsupportedInfo<{spec.FullName}>(this, {ContextParser.Literal(spec.UnsupportedReason)})",
	};

	private static string CreateObject(TypeSpec spec, ObjectSpec value)
	{
		var properties = value.Properties.Select(p => $"{Services}.CreatePropertyInfo<{spec.FullName}, {p.Type.FullName}>(name: {ContextParser.Literal(p.Name)}, typeInfo: {p.Type.Accessor}, getter: {p.Getter ?? "null"}, setter: {p.Setter ?? "null"}, explicitName: {ContextParser.Literal(p.ExplicitName)}, isRequired: {Bool(p.IsRequired)}, writeOrder: {p.WriteOrder})");
		var parameters = value.Parameters?.Select(p => $"{Services}.CreateParameterInfo<{p.Type.FullName}>(name: {ContextParser.Literal(p.Name)}, typeInfo: {p.Type.Accessor}, explicitName: {ContextParser.Literal(p.ExplicitName)}, boundProperty: {ContextParser.Literal(p.BoundProperty)}, isOptional: {Bool(p.IsOptional)}, defaultValue: {p.DefaultValue})");
		var (createObject, createObjectWithArguments) = value.Parameters is null ? (value.Create, "null") : ("null", value.Create);
		return $"{Services}.CreateObjectInfo<{spec.FullName}>(this, createObject: {createObject}, createObjectWithArguments: {createObjectWithArguments}, properties: () => [{String.Join(", ", properties)}], parameters: {(parameters is null ? "null" : $"() => [{String.Join(", ", parameters)}]")}, setsRequiredMembers: {Bool(value.SetsRequiredMembers)})";
	}

	private static string CreatePolymorphic(TypeSpec spec, PolymorphicSpec value)
	{
		var derived = value.DerivedTypes.Select(static d => $"{Services}.CreateDerivedTypeInfo<{d.Type.FullName}>({d.Type.Accessor}, {ContextParser.Literal(d.Discriminator)}{String.Concat(d.Aliases.Select(static a => ", " + ContextParser.Literal(a)))})");
		return $"{Services}.CreatePolymorphicInfo<{spec.FullName}>(this, {ContextParser.Literal(value.DiscriminatorName)}, {Bool(value.CaseInsensitive)}, (global::PeterJuhasz.Text.Yaml.Serialization.YamlUnknownDerivedTypeHandling)({value.UnknownDerivedTypeHandling}), [{String.Join(", ", derived)}], {value.Fallback?.Accessor ?? "null"})";
	}

	private static string Bool(bool value) => value ? "true" : "false";

	private sealed class CodeWriter
	{
		private readonly StringBuilder builder = new();
		private int indent;

		public void Line(string text = "")
		{
			if (text.Length > 0)
			{
				builder.Append('\t', indent);
			}
			builder.Append(text).Append('\n');
		}

		public void Open(string header)
		{
			Line(header);
			Line("{");
			indent++;
		}

		public void Close()
		{
			indent--;
			Line("}");
		}

		public override string ToString() => builder.ToString();
	}
}
